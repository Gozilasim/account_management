export const translations: Record<SupportedLanguage, Record<TranslationKey, string>> = {
  en,
  "zh-CN": zh
};

// ###############################################
// Helpers
// ###############################################

export function resolveSupportedLanguage(locale: string | null | undefined): SupportedLanguage {
  const normalized = locale?.trim().toLowerCase();
  if (!normalized) return "en";
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return "en";
}

export function isKnownLanguageLocale(locale: string | null | undefined): boolean {
  const normalized = locale?.trim().toLowerCase();
  return Boolean(normalized && (normalized === "en" || normalized.startsWith("en-") || normalized === "zh" || normalized.startsWith("zh-")));
}

export function localeForLanguage(language: SupportedLanguage): string {
  return LANGUAGE_OPTIONS.find((option) => option.value === language)?.locale ?? "en-US";
}

export function labelForLocale(locale: string | null | undefined, emptyLabel: string): string {
  if (!locale) return emptyLabel;
  const known = LANGUAGE_OPTIONS.find((option) => option.value === resolveSupportedLanguage(locale) && isKnownLanguageLocale(locale));
  return known ? known.label : locale;
}

export function translate(language: SupportedLanguage, key: TranslationKey, values?: Record<string, string | number>): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  if (!values) return template;
  return Object.entries(values).reduce((text, [name, value]) => text.split(`{${name}}`).join(String(value)), template);
}
